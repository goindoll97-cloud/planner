def _book(sheets):
    from openpyxl import Workbook
    from openpyxl.styles import Font
    book = Workbook()
    book.remove(book.active)
    for title, (headers, rows) in sheets.items():
        sheet = book.create_sheet(title)
        sheet.append(list(headers))
        for cell in sheet[1]:
            cell.font = Font(bold=True)
        for row in rows:
            sheet.append([row.get(h, "") for h in headers])
        for column in sheet.columns:
            sheet.column_dimensions[column[0].column_letter].width = max(12, min(40, max(len(str(c.value or "")) for c in column) + 4))
    out = BytesIO()
    book.save(out)
    return out.getvalue()


def _doc(title, sections):
    from docx import Document
    doc = Document()
    doc.add_heading(title, level=1)
    doc.add_paragraph("가상 회사 연습 자료입니다. 모든 내용은 허구입니다.")
    for heading, rows in sections:
        doc.add_heading(heading, level=2)
        if isinstance(rows, str):
            doc.add_paragraph(rows)
            continue
        table = doc.add_table(rows=0, cols=2)
        table.style = "Table Grid"
        for label, value in rows:
            cells = table.add_row().cells
            cells[0].text, cells[1].text = str(label), str(value)
    out = BytesIO()
    doc.save(out)
    return out.getvalue()


